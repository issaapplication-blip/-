-- RAFIQ Telegram bookings.
-- Non-destructive: creates a new table and does not modify existing platform tables.
create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  telegram_user_id bigint not null,
  telegram_username text,
  full_name text not null check (char_length(full_name) between 1 and 120),
  city text not null check (char_length(city) between 1 and 120),
  service_key text not null check (service_key in ('lab', 'radiology', 'physio')),
  service_label text not null,
  status text not null default 'new' check (status in ('new', 'in_review', 'contacted', 'closed', 'cancelled')),
  created_at timestamptz not null default now()
);

create index if not exists bookings_created_at_idx
  on public.bookings (created_at desc);
create index if not exists bookings_status_created_at_idx
  on public.bookings (status, created_at desc);

alter table public.bookings enable row level security;

-- The bot uses the server-side service-role key only. Do not expose it to a browser/client.
revoke all on table public.bookings from anon, authenticated;
grant select, insert, update on table public.bookings to service_role;
grant usage, select on sequence public.bookings_id_seq to service_role;

comment on table public.bookings is
  'RAFIQ Telegram service requests. Contains contact-identifying data; access is server-side only.';
